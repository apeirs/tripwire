#!/usr/bin/env node
// Writes demo/arm/contracts.js: the ABIs and creation bytecode the arm page uses, taken from Foundry's out/ (run
// `forge build` first). The page needs no build step; this file is regenerated only when the contracts change.
//
//   node demo/arm/tools/build-contracts.mjs           # write contracts.js
//   node demo/arm/tools/build-contracts.mjs --check   # exit 1 if contracts.js is out of date with out/
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const target = resolve(here, "../contracts.js");

// Bytecode only where the page deploys the contract; Intent and PanicButton go through the CREATE2 factory so they
// land at the same address on every chain, like script/DeploySignals.s.sol.
const WANT = { TripwireReactive: true, Guardian: true, Intent: true, PanicButton: true };

const out = {};
for (const [name, withCode] of Object.entries(WANT)) {
  const f = resolve(root, `out/${name}.sol/${name}.json`);
  if (!existsSync(f)) throw new Error(`${f} missing: run forge build`);
  const j = JSON.parse(readFileSync(f, "utf8"));
  out[name] = { abi: j.abi };
  if (withCode) out[name].bytecode = j.bytecode.object;
}

const body =
  "// Generated by demo/arm/tools/build-contracts.mjs from Foundry's out/ (forge build). Do not edit by hand.\n" +
  "export const CONTRACTS = " + JSON.stringify(out) + ";\n";

if (process.argv.includes("--check")) {
  const cur = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (cur !== body) {
    console.error("demo/arm/contracts.js is out of date with out/: run node demo/arm/tools/build-contracts.mjs");
    process.exit(1);
  }
  console.log("contracts.js matches out/");
} else {
  writeFileSync(target, body);
  console.log(`wrote ${target} (${(body.length / 1024).toFixed(1)} KiB)`);
}
